CountdownResources::~CountdownResources() {
	delete _font1;
	delete _font2;
	delete _bitFont;
}

void CountdownResources::load(Common::SeekableReadStream &s) {
	Resources::load(s);
	s.seek(findEntry(_vm->getGameID(), 2, 0, (Common::Language)0));

	uint count = s.readUint16LE();
	_cursors.resize(count);
	for (uint i = 0; i < count; ++i) {
		uint size = s.readUint16LE();
		_cursors[i].resize(size);
		s.read(_cursors[i].data(), size);
	}

	_font1 = new MartianFont(7, s);
	_font2 = new MartianFont(7, s);
	_bitFont = new MartianBitFont(ARRAYSIZE(BITFONT_DATA) / 8, BITFONT_DATA);
}

Common::Array<CellIdent> CountdownResources::loadCells(Common::SeekableReadStream &s) const {
	Common::Array<CellIdent> cells;
	for (byte cell = s.readByte(); cell != 0xff; cell = s.readByte()) {
		if (cell == 100)
			cell = 8;
		assert(cell < ARRAYSIZE(CHARACTER_FILES));
		uint16 file = CHARACTER_FILES[cell];
		cells.push_back(CellIdent(cell, file & 0xff, file >> 8));
	}
	return cells;
}

CharEntry CountdownResources::loadCharEntry(const byte *data) const {
	Common::MemoryReadStream s(data, 999);
	CharEntry entry;
	entry._estabIndex = -1;
	entry._numColors = 256;
	entry._cells = loadCells(s);
	entry._animFile.load(s);
	entry._paletteFile.load(s);
	entry._scriptFile.load(s);
	return entry;
}

const byte *CountdownResources::getCursor(int num) const {
	assert(num >= 0 && num < (int)_cursors.size());
	return _cursors[num].data();
}

int CountdownResources::getRMouse(int i, int j) const {
	if (i >= ARRAYSIZE(RMOUSE))
		return -1;
	return RMOUSE[i][j];
}

int CountdownResources::inButtonXRange(int x) const {
	for (int i = 0; i < ARRAYSIZE(RMOUSE); ++i) {
		if (x >= RMOUSE[i][0] && x < RMOUSE[i][1])
			return i;
	}
	return -1;
}

